package com.example.unigearmanager

import android.content.Intent
import android.os.Bundle
import android.text.Editable
import android.text.TextWatcher
import android.view.View
import android.widget.TextView
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import com.google.android.material.button.MaterialButton
import com.google.android.material.textfield.TextInputEditText
import com.google.android.material.textfield.TextInputLayout

class StudentLoginActivity : AppCompatActivity() {
    private var signUpMode = false
    private var autoGeneratedEmail = ""

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_student_login)

        val backButton = findViewById<MaterialButton>(R.id.btnBackStudent)
        val studentIdInputLayout = findViewById<TextInputLayout>(R.id.studentIdInputLayout)
        val emailInputLayout = findViewById<TextInputLayout>(R.id.emailStudentInputLayout)
        val passwordInputLayout = findViewById<TextInputLayout>(R.id.passwordStudentInputLayout)
        val confirmPasswordInputLayout = findViewById<TextInputLayout>(R.id.confirmPasswordStudentInputLayout)
        val studentIdInput = findViewById<TextInputEditText>(R.id.studentIdInput)
        val emailInput = findViewById<TextInputEditText>(R.id.emailStudentInput)
        val passwordInput = findViewById<TextInputEditText>(R.id.passwordStudentInput)
        val confirmPasswordInput = findViewById<TextInputEditText>(R.id.confirmPasswordStudentInput)
        val loginButton = findViewById<MaterialButton>(R.id.btnStudentLoginSubmit)
        val signUpLink = findViewById<TextView>(R.id.tvStudentSignUp)

        backButton.setOnClickListener {
            startActivity(Intent(this, MainActivity::class.java))
            finish()
        }

        // Auto-populate email when student ID is entered
        studentIdInput.addTextChangedListener(object : TextWatcher {
            override fun beforeTextChanged(s: CharSequence?, start: Int, count: Int, after: Int) = Unit
            override fun onTextChanged(s: CharSequence?, start: Int, before: Int, count: Int) {
                val studentId = s?.toString()?.toIntOrNull() ?: 0
                if (studentId in 1..10) {
                    val studentName = UniWearRepository.getStudentName(studentId)
                    val email = studentName.lowercase() + "@student.edu"
                    if (emailInput.text.isNullOrBlank() || emailInput.text.toString() == autoGeneratedEmail) {
                        autoGeneratedEmail = email
                        emailInput.setText(email)
                    }
                }
            }
            override fun afterTextChanged(s: Editable?) = Unit
        })

        loginButton.setOnClickListener {
            val form = validateStudentForm(
                studentIdInputLayout,
                emailInputLayout,
                passwordInputLayout,
                confirmPasswordInputLayout,
                studentIdInput.text?.toString()?.trim().orEmpty(),
                emailInput.text?.toString()?.trim().orEmpty(),
                passwordInput.text?.toString().orEmpty(),
                confirmPasswordInput.text?.toString().orEmpty(),
                requireConfirmation = signUpMode
            ) ?: return@setOnClickListener

            if (signUpMode) {
                if (UniWearRepository.studentAccounts.any { it.userId == form.userId } ||
                    getSharedPreferences(STUDENT_ACCOUNTS, MODE_PRIVATE).contains("${form.userId}.password")) {
                    passwordInputLayout.error = "An account already exists for this Student ID"
                    return@setOnClickListener
                }
                saveStudentAccount(form)
                Toast.makeText(this, "Student account created.", Toast.LENGTH_SHORT).show()
                openStudentDashboard(form.studentId, form.studentName)
            } else {
                UniWearRepository.getStudentAccount(form.userId) { account ->
                    runOnUiThread {
                        val valid = account?.let {
                            it.passwordHash == passwordHash(form.password) && it.email.equals(form.email, ignoreCase = true)
                        } ?: canLogIn(form)
                        if (valid) {
                            Toast.makeText(this, "Welcome ${account?.studentName ?: form.studentName}!", Toast.LENGTH_SHORT).show()
                            openStudentDashboard(form.studentId, account?.studentName ?: form.studentName)
                        } else {
                            passwordInputLayout.error = "Account not found or password is incorrect"
                        }
                    }
                }
            }
        }

        signUpLink.setOnClickListener {
            signUpMode = !signUpMode
            confirmPasswordInputLayout.visibility = if (signUpMode) View.VISIBLE else View.GONE
            loginButton.text = if (signUpMode) "Sign Up" else "Log In"
            signUpLink.text = if (signUpMode) "Log In" else "Sign Up"
        }
    }

    private fun validateStudentForm(
        studentIdInputLayout: TextInputLayout,
        emailInputLayout: TextInputLayout,
        passwordInputLayout: TextInputLayout,
        confirmPasswordInputLayout: TextInputLayout,
        userId: String,
        email: String,
        password: String,
        confirmPassword: String,
        requireConfirmation: Boolean
    ): StudentAuthForm? {
        studentIdInputLayout.error = null
        emailInputLayout.error = null
        passwordInputLayout.error = null
        confirmPasswordInputLayout.error = null

        var hasError = false
        AuthRules.studentIdError(userId)?.let {
            studentIdInputLayout.error = it
            hasError = true
        }
        AuthRules.emailError(email)?.let {
            emailInputLayout.error = it
            hasError = true
        }
        AuthRules.passwordError(password)?.let {
            passwordInputLayout.error = it
            hasError = true
        }
        if (requireConfirmation && password != confirmPassword) {
            confirmPasswordInputLayout.error = "Password confirmation must match password"
            hasError = true
        }

        if (hasError) return null
        val numericId = userId.toIntOrNull()?.takeIf { it in 1..10 } ?: 0
        val name = UniWearRepository.getStudentName(numericId).takeIf { numericId in 1..10 }
            ?: email.substringBefore("@").replaceFirstChar { it.uppercase() }
        return StudentAuthForm(userId, email, password, numericId, name)
    }

    private fun saveStudentAccount(form: StudentAuthForm) {
        getSharedPreferences(STUDENT_ACCOUNTS, MODE_PRIVATE)
            .edit()
            .putString("${form.userId}.email", form.email)
            .putString("${form.userId}.password", form.password)
            .putString("${form.userId}.name", form.studentName)
            .apply()
        UniWearRepository.saveStudentAccount(
            StudentAccount(form.userId, form.email, passwordHash(form.password), form.studentName)
        )
    }

    private fun passwordHash(password: String): String = java.security.MessageDigest
        .getInstance("SHA-256")
        .digest(password.toByteArray(Charsets.UTF_8))
        .joinToString("") { "%02x".format(it) }

    private fun canLogIn(form: StudentAuthForm): Boolean {
        val prefs = getSharedPreferences(STUDENT_ACCOUNTS, MODE_PRIVATE)
        val savedPassword = prefs.getString("${form.userId}.password", null)
        if (savedPassword != null) {
            return savedPassword == form.password &&
                prefs.getString("${form.userId}.email", "").equals(form.email, ignoreCase = true)
        }
        return false
    }

    private fun openStudentDashboard(studentId: Int, studentName: String) {
        startActivity(Intent(this, StudentDashboardActivity::class.java).apply {
            putExtra("STUDENT_ID", studentId)
            putExtra("STUDENT_NAME", studentName)
        })
        finish()
    }

    private data class StudentAuthForm(
        val userId: String,
        val email: String,
        val password: String,
        val studentId: Int,
        val studentName: String
    )

    private companion object {
        const val STUDENT_ACCOUNTS = "student_accounts"
    }
}
